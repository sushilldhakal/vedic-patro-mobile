export function useTranslation() {
  const { pick } = useLocale();
  const t = useCallback(
    (key: string) => {
      const pair = STRINGS[key];
      return pair ? pick(pair[0], pair[1]) : key;
    },
    [pick],
  );
  return { t, i18n: { language: "ne" } };
}
